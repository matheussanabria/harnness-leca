// Vite plugin: writes dist/islands.js, a map from island name to its hashed entry file and CSS.
// The legacy loader imports it instead of the JSON manifest, so the server needs no new MIME type.
import type { Plugin } from "vite";

interface IslandEntry {
  file: string;
  css: string[];
}

export function islandsIndex(): Plugin {
  return {
    name: "harness-islands-index",
    generateBundle(_options, bundle) {
      const islands: Record<string, IslandEntry> = {};
      for (const chunk of Object.values(bundle)) {
        if (chunk.type !== "chunk" || !chunk.isEntry) continue;
        const css = [...(chunk.viteMetadata?.importedCss ?? [])];
        islands[chunk.name] = { file: chunk.fileName, css };
      }
      this.emitFile({
        type: "asset",
        fileName: "islands.js",
        source: `// Generated by ui/web/build/islands-index.ts. Do not edit.\nexport default ${JSON.stringify(islands, null, 2)};\n`,
      });
    },
  };
}
