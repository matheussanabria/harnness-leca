/** Generates the guidance files of the handoff bundle so another person (with Claude or any engine) can keep prototyping. */

/**
 * @param {{ slug: string, prototypes: { id: string, title: string, screens: number }[], hasDs: boolean, mcp: { name: string, dir: string, entry: string }[], generatedAt: string }} m
 */
function buildReadme(m) {
  const protoLines = m.prototypes.map((p) => `- \`prototypes/${p.id}/\` - ${p.title} (${p.screens} screen(s)); standalone preview in \`standalone/${p.id}.html\``).join("\n") || "- (none)";
  const mcpLines = m.mcp.map((s) => `- \`${s.name}\`: \`mcp/${s.name}/${s.entry}\` (run \`npm install\` once inside \`mcp/${s.name}/\`)`).join("\n");
  return `# ${m.slug} - prototype and design system handoff

Generated by Harness Atelier on ${m.generatedAt}. This bundle lets you continue prototyping with Claude Code, Codex, Gemini or any
agent engine while following the same patterns as the original project.

## What is inside

${protoLines}
${m.hasDs ? "- `design-system/` - tokens, theme, registry and component sources (HTML, CSS, JS, Angular, React)" : ""}
${mcpLines ? `\n## MCP servers\n\n${mcpLines}\n\n\`.mcp.json\` already points to them with relative paths.` : ""}
- \`AGENTS.md\` / \`CLAUDE.md\` - rules the agent must follow
- \`MAPA.md\` - file index (read it first, do not scan the tree)
- \`manifest.json\` - machine-readable summary of this bundle

## How to continue

1. Unzip the bundle. Node 18+ is the only requirement.
2. \`npm run preview\` - serves the prototypes at http://localhost:4400 and opens the browser (\`PORT=5000 npm run preview\` to change the port).${m.mcp.length ? "\n3. `npm run setup` - installs the MCP server dependencies (once)." : ""}
${m.mcp.length ? "4" : "3"}. Open the folder in your agent engine (Claude Code: \`claude\` inside the folder) and approve the servers from \`.mcp.json\`.
${m.mcp.length ? "5" : "4"}. Ask the agent to edit a screen or create a new one. It must read \`MAPA.md\` and \`AGENTS.md\` first.

Without Node, open \`standalone/<id>.html\` directly in a browser. You can also re-import \`prototypes/<id>/\` into Harness Atelier.
`;
}

/** @param {{ slug: string, hasDs: boolean, mcp: { name: string }[] }} m */
function buildAgents(m) {
  const mcpRule = m.mcp.length
    ? `- Get components and boilerplates from the MCP server(s) ${m.mcp.map((s) => `\`${s.name}\``).join(", ")} before writing markup by hand.`
    : "- Reuse components from `design-system/components/` before writing markup by hand.";
  return `# Agent rules - ${m.slug}

Read \`MAPA.md\` first. Edit only the files it points to; never scan the whole tree.

## Prototype rules
- A prototype lives in \`prototypes/<id>/\`: \`proto.json\` (screens list), \`screens/*.html\`, \`styles/\`, \`data/\`, \`MAPA.md\`.
- Every element carries a unique \`data-pid\`; roots of design-system components carry \`data-component="<name>"\`.
- Navigation uses \`data-action="goto:<screen-id>"\`; the screen id must exist in \`proto.json\`.
- Keep edits to a prototype consistent with its own \`MAPA.md\`; update that file when screens change.

## Design system rules
${m.hasDs ? "- Tokens come from `design-system/tokens.css` and `design-system/theme.css`; use semantic tokens (`var(--...)`), never raw colors." : ""}
${mcpRule}
- Icons: FontAwesome only (\`fa-solid\` / \`fa-regular\`). No emojis in UI or code.

## Working rules
- Keep files between 150 and 250 lines (hard cap 300); split by responsibility instead of growing one file.
- When you create, move or delete a file, update \`MAPA.md\` in the same task.
- Never delete files or data without explicit confirmation from the user.
`;
}

/**
 * @param {{ slug: string, prototypes: { id: string, title: string }[], files: string[], hasDs: boolean }} m
 */
function buildMapa(m) {
  const rows = [
    "| `README.md` | How to open and continue this bundle. |",
    "| `AGENTS.md`, `CLAUDE.md` | Rules for any agent engine (CLAUDE.md points to AGENTS.md). |",
    "| `manifest.json` | Machine-readable summary (prototypes, design system, MCP servers). |",
    "| `.mcp.json` | MCP servers with relative paths. |",
    "| `package.json` | Scripts: `npm run preview` (local preview) and `npm run setup` (MCP dependencies). |",
    "| `tools/preview-server.js` | Dependency-free local server for `standalone/`, `prototypes/` and `design-system/`. |",
    ...m.prototypes.map((p) => `| \`prototypes/${p.id}/\` | ${p.title}: \`proto.json\`, \`screens/\`, \`styles/\`, \`data/\`, own \`MAPA.md\`. |`),
    ...m.prototypes.map((p) => `| \`standalone/${p.id}.html\` | Self-contained preview of ${p.title}. |`),
    ...(m.hasDs ? [
      "| `design-system/tokens.css`, `design-system/theme.css` | Design tokens and theme. |",
      "| `design-system/components/<name>/` | Component sources and `manifest.json` (HTML, CSS, JS, Angular, React). |",
      "| `design-system/registry.json` | Component registry used by the MCP server. |",
    ] : []),
    "| `mcp/<server>/` | MCP server source (install dependencies before use). |",
  ];
  return `# ${m.slug} map

Entry point for agents: find files and responsibilities here instead of scanning the bundle.

| File | Responsibility |
|---|---|
${rows.join("\n")}
`;
}

/** @param {{ name: string, entry: string, env: Record<string, string> }[]} sources */
function buildMcpJson(sources) {
  const mcpServers = {};
  for (const s of sources) {
    const env = {};
    for (const [key, value] of Object.entries(s.env || {})) {
      env[key] = /DESIGN_SYSTEM_DIR$/.test(key) ? "./design-system" : value;
    }
    mcpServers[s.name] = { command: "node", args: [`mcp/${s.name}/${s.entry}`], ...(Object.keys(env).length ? { env } : {}) };
  }
  return JSON.stringify({ mcpServers }, null, 2) + "\n";
}

/**
 * package.json of the bundle: `preview` serves the prototypes, `setup` installs each MCP server's dependencies.
 * @param {string} slug
 * @param {{ name: string }[]} sources
 */
function buildPackageJson(slug, sources) {
  const scripts = { preview: "node tools/preview-server.js --open" };
  if (sources.length) scripts.setup = sources.map((s) => `npm --prefix mcp/${s.name} install`).join(" && ");
  return JSON.stringify({ name: `${slug}-handoff`, version: "1.0.0", private: true, description: "Prototype and design system handoff", scripts }, null, 2) + "\n";
}

module.exports = { buildReadme, buildAgents, buildMapa, buildMcpJson, buildPackageJson };
