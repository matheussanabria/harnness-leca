// @ts-check
"use strict";

/**
 * Token file and compact index for a ".dc.html" Design System.
 * The source file defines almost none of the semantic tokens its components read, so the project
 * supplies a palette (a flat map of custom property name to value) and this module reports what is missing.
 */

const { classNames } = require("./extract-dc");

/**
 * @param {{ name?: string, tokens: Record<string, string> }} palette
 * @param {string[]} required tokens the components read
 */
function buildTokensCss(palette, required) {
  const entries = Object.entries(palette.tokens || {});
  const missing = required.filter((name) => !(name in (palette.tokens || {})));
  const lines = entries.map(([name, value]) => `  ${name}: ${value};`);
  const css = `/* Design tokens (${palette.name || "palette"}). Generated by tools/import-dc-design-system.js. */\n:root {\n${lines.join("\n")}\n}\n`;
  return { css, missing };
}

/**
 * Element defaults the components assume (links inside the header, buttons rendered as links, box sizing).
 * The source Design System file does not ship them, so without this the header links render in default blue
 * and `<a class="btn">` is underlined and top-aligned. Lives in components.css, which the sandbox loads only
 * for prototypes that opt in, so older prototypes are not restyled.
 */
const BASE_CSS = `/* Base layer (pilot). Not part of the source Design System file. */
*,*::before,*::after{box-sizing:border-box}
body{margin:0;font-family:var(--font-sans);color:var(--neutral-body);background:var(--neutral-background);-webkit-font-smoothing:antialiased}
img,svg{max-width:100%}
a{color:var(--primary-interactive)}
:where(.header,.footer) a{color:inherit;text-decoration:none}
.btn{display:inline-flex;align-items:center;justify-content:center;gap:8px;text-decoration:none}
:focus-visible{outline:2px solid var(--highlight-focus);outline-offset:2px}
`;

/**
 * Base layer, the component CSS (a header per component), then the palette's own overrides.
 * Overrides fix source colours that are hardcoded for another brand (for example the footer strip).
 */
function buildComponentsCss(components, overrides = "") {
  const body = `${BASE_CSS}\n${components.map((c) => `/* ${c.name} (${c.id}) */\n${c.css.trim()}\n`).join("\n")}`;
  return overrides.trim() ? `${body}\n/* Palette overrides */\n${overrides.trim()}\n` : body;
}

const TOKEN_ROLES = {
  "--primary-interactive": "buttons, links and active controls",
  "--primary-dark": "hover and pressed state of primary actions",
  "--primary-headings": "headings and strong brand text",
  "--primary-background": "soft brand-tinted surfaces",
  "--neutral-dark": "strong text",
  "--neutral-base": "secondary text and icons",
  "--neutral-muted": "borders of inputs and controls",
  "--neutral-light": "dividers and disabled fills",
  "--neutral-background": "page and card surfaces",
  "--highlight-focus": "keyboard focus ring",
  "--highlight-dark": "environment banner",
  "--font-sans": "body text",
  "--font-display": "display headings",
  "--font-mono": "labels and code",
  "--spacing-scale-base": "grid gap and spacing unit",
};
const STATUS_ROLES = { base: "status colour", dark: "status text", background: "status surface", muted: "status border" };

/** Short purpose of a token, or an empty string when unknown. */
function tokenRole(name) {
  if (TOKEN_ROLES[name]) return TOKEN_ROLES[name];
  const status = /^--(danger|success|warning)-(base|dark|background|muted)$/.exec(name);
  return status ? `${status[1]} ${STATUS_ROLES[status[2]]}` : "";
}

/**
 * Compact index the prompt reads: token names with their roles, then one line per component.
 * @param {Array<{id:string,name:string,states:string,html:string}>} components
 * @param {string[]} tokenNames
 */
function buildIndex(components, tokenNames, paletteName = "palette") {
  const rows = components.map((c) => `- ${c.id} | ${c.name} | ${c.states} | classes: ${classNames(c.html).slice(0, 8).join(" ")}`);
  const tokenRows = tokenNames.map((name) => (tokenRole(name) ? `${name}: ${tokenRole(name)}` : name));
  return [
    "# Design System index",
    "",
    `Palette: ${paletteName}. Use these components and class names; do not invent equivalents. Colours, spacing and fonts come from the tokens below.`,
    "",
    "## Tokens (name: role)",
    ...tokenRows,
    "",
    "## Components (id | name | states | classes)",
    ...rows,
    "",
  ].join("\n");
}

module.exports = { buildTokensCss, buildComponentsCss, buildIndex, BASE_CSS };
